def _object(value: Any) -> dict[str, Any]:
    return value if isinstance(value, dict) else {}


def _text(value: Any) -> str:
    return value.strip() if isinstance(value, str) else ""


def _schema_version(manifest: dict[str, Any]) -> int:
    return 3 if manifest.get("schema") == _HATCH_V3_SCHEMA else 0


def _mode(raw: dict[str, Any]) -> str:
    if not raw:
        return "unresolved"
    value = raw.get("mode")
    if value is None:
        return "present"
    mode = _text(value).lower()
    return mode if mode in _SECTION_MODES else "invalid"


def _section_heading(index: int, title: str) -> str:
    label = _CN_SECTION_NUMBERS[index] if index < len(_CN_SECTION_NUMBERS) else str(index)
    return f"## {label}、{title}"


def _get_main_plotline(manifest: dict[str, Any]) -> dict[str, Any]:
    """Read the canonical v3 main plotline shape without aliases."""
    raw = manifest.get("main_plotline")
    if not isinstance(raw, dict):
        return {"mode": "invalid", "progression_arc": [], "_shape_valid": False}

    raw_arc = raw.get("progression_arc")
    arc_shape_valid = isinstance(raw_arc, list)
    progression_arc: list[dict[str, str]] = []
    if isinstance(raw_arc, list):
        for item in raw_arc:
            if not isinstance(item, dict):
                arc_shape_valid = False
                continue
            progression_arc.append({
                "stage": _text(item.get("stage")),
                "goal": _text(item.get("goal")),
            })
    return {
        "mode": _mode(raw),
        "core_quest": _text(raw.get("core_quest")),
        "driving_force": _text(raw.get("driving_force")),
        "progression_arc": progression_arc,
        "volume1_hook": _text(raw.get("volume1_hook")),
        "endgame_condition": _text(raw.get("endgame_condition")),
        "_shape_valid": arc_shape_valid,
    }


