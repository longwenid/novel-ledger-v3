    if story_errors:
        _v3_error("step4_outline.story_map", story_errors[0]["message"])
    _normalized_long_term_commitments(step4)

    volume1 = _object(manifest.get("step5_volume1"))
    for key in ("title", "spine", "climax", "next_volume_hook"):
        if not _text(volume1.get(key)):
            _v3_error("step5_volume1", f"missing required field: {key}")
