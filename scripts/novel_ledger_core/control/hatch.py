    if (mechanism.get("mode") == "none") != (mechanism_decision.get("status") == "none"):
        _v3_error("story_mechanism", "must match the story_mechanism decision")
    _validate_v3_mode_section(
        manifest,
        "material_life",
        _get_sustenance_craft(manifest),
        ("profession", "income_loop", "social_network"),
    )
    _validate_v3_mode_section(
        manifest,
        "long_arc_question",
        _get_world_mystery(manifest),
        ("core_mystery", "surface_illusion"),
    )

    plotline = _get_main_plotline(manifest)
    if not isinstance(manifest.get("main_plotline"), dict) or plotline.get("mode") != "present":
        _v3_error("main_plotline", "must be an explicit object")
    for key in ("core_quest", "driving_force", "volume1_hook", "endgame_condition"):
        if not _text(plotline.get(key)):
            _v3_error("main_plotline", f"missing required field: {key}")
    arc = plotline.get("progression_arc")
    if not isinstance(arc, list) or not 2 <= len(arc) <= 5:
        _v3_error("main_plotline.progression_arc", "must contain 2-5 causal stages")
    for index, item in enumerate(arc):
        if not _text(item.get("stage")) or not _text(item.get("goal")):
            _v3_error(f"main_plotline.progression_arc[{index}]", "stage and goal are required")

    long_arc = _get_world_mystery(manifest)
