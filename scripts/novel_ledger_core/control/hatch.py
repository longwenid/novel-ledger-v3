def _get_world_mystery(manifest: dict[str, Any]) -> dict[str, Any]:
    """Read the canonical v3 long-arc shape without aliases."""
    raw = manifest.get("long_arc_question")
    if not isinstance(raw, dict):
        return {"mode": "invalid", "decryption_ladder": [], "_shape_valid": False}

    raw_ladder = raw.get("decryption_ladder", [])
    ladder_shape_valid = isinstance(raw_ladder, list)
    decryption_ladder: list[dict[str, str]] = []
    if isinstance(raw_ladder, list):
        for item in raw_ladder:
            if not isinstance(item, dict):
                ladder_shape_valid = False
                continue
            decryption_ladder.append({
                "stage": _text(item.get("stage")),
                "truth": _text(item.get("truth")),
            })
    return {
        "mode": _mode(raw),
        "core_mystery": _text(raw.get("core_mystery")),
        "surface_illusion": _text(raw.get("surface_illusion")),
        "decryption_ladder": decryption_ladder,
        "_shape_valid": ladder_shape_valid,
    }


def _v3_error(field: str, message: str) -> None:
    raise LedgerError("invalid_hatch_v3", f"{field}: {message}", {"field": field})


def _normalized_long_term_commitments(step4: dict[str, Any]) -> list[dict[str, Any]]:
    """Give book-level promises stable IDs shared by the plan and rendered outline."""
    raw = step4.get("long_term_commitments")
    if raw is None:
        return []
    if not isinstance(raw, list):
        _v3_error("step4_outline.long_term_commitments", "must be a list")

    spine = _object(step4.get("event_spine"))
    subplots = spine.get("subplots")
    arc_ids = {
        _text(owner.get("id"))
        for owner in [spine.get("mainline"), *(subplots if isinstance(subplots, list) else [])]
        if isinstance(owner, dict) and _text(owner.get("id"))
    }
    normalized: list[dict[str, Any]] = []
    seen_ids: set[str] = set()
    for index, item in enumerate(raw, 1):
        field = f"step4_outline.long_term_commitments[{index - 1}]"
        if not isinstance(item, dict):
            _v3_error(field, "must be an object")
        supplied_id = item.get("id")
        if supplied_id is None or (isinstance(supplied_id, str) and not supplied_id.strip()):
            ident = f"commitment-{index:04d}"
        elif isinstance(supplied_id, str):
            ident = supplied_id.strip()
        else:
            _v3_error(f"{field}.id", "must be a non-empty string when supplied")
        if ident in seen_ids:
            _v3_error(f"{field}.id", f"duplicate commitment id: {ident}")
        seen_ids.add(ident)

        promise = _text(item.get("promise"))
        if not promise:
            _v3_error(f"{field}.promise", "must be a non-empty string")
        planted = item.get("planted_volume")
        resolved = item.get("resolved_volume")
        for name, value in (("planted_volume", planted), ("resolved_volume", resolved)):
            if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
                _v3_error(f"{field}.{name}", "must be a positive integer")
        if planted > resolved:
            _v3_error(field, "planted_volume must not exceed resolved_volume")

        description = item.get("description", "")
        if not isinstance(description, str):
            _v3_error(f"{field}.description", "must be a string")
        entry: dict[str, Any] = {
            "id": ident,
            "promise": promise,
            "planted_volume": planted,
            "resolved_volume": resolved,
            "description": description.strip(),
        }
        if "arc_ref" in item:
            arc_ref = _text(item["arc_ref"])
            if arc_ref not in arc_ids:
                _v3_error(f"{field}.arc_ref", "must reference an event_spine mainline or subplot id")
            entry["arc_ref"] = arc_ref
        for name in ("seed_use", "final_condition"):
            if name in item:
                value = item[name]
                if not isinstance(value, str):
                    _v3_error(f"{field}.{name}", "must be a string")
                entry[name] = value.strip()
        normalized.append(entry)
    return normalized


def _validate_text_list(field: str, value: Any, *, minimum: int = 1, maximum: int | None = None) -> list[str]:
    if not isinstance(value, list):
        _v3_error(field, "must be a list")
    cleaned = [_text(item) for item in value]
    if any(not item for item in cleaned):
        _v3_error(field, "must contain only non-empty strings")
    if len(cleaned) < minimum:
        _v3_error(field, f"must contain at least {minimum} item(s)")
    if maximum is not None and len(cleaned) > maximum:
        _v3_error(field, f"must contain at most {maximum} item(s)")
    if len(set(cleaned)) != len(cleaned):
        _v3_error(field, "must not contain duplicates")
    return cleaned


def _validate_guided_decisions(manifest: dict[str, Any]) -> dict[str, dict[str, Any]]:
    wizard = _object(manifest.get("wizard"))
    if wizard.get("mode") != "guided":
        _v3_error("wizard.mode", "must be guided")
    if wizard.get("status") != "confirmed":
        raise LedgerError(
            "hatch_unresolved",
            "guided hatch is not fully confirmed",
            {"field": "wizard.status"},
        )
    if wizard.get("final_confirmation") is not True:
        raise LedgerError(
            "hatch_unresolved",
            "guided hatch requires one final start confirmation",
            {"field": "wizard.final_confirmation"},
        )

    raw_decisions = wizard.get("decisions")
    if not isinstance(raw_decisions, list):
        _v3_error("wizard.decisions", "must be a list")
    raw_ids = [_text(item.get("id")) if isinstance(item, dict) else "" for item in raw_decisions]
    if raw_ids == list(_LEGACY_GUIDED_DECISION_IDS):
        # Already confirmed v3 manifests used one combined scale/voice gate.
        decision_ids = _LEGACY_GUIDED_DECISION_IDS
    else:
        # New manifests retain every base gate in order. Additional questions may
        # follow any base gate when their independent reason is recorded.
        decision_ids = _GUIDED_DECISION_IDS
        base_index = 0
        latest_base = ""
        extra_ids: set[str] = set()
        for index, raw in enumerate(raw_decisions):
            field = f"wizard.decisions[{index}]"
            if not isinstance(raw, dict):
                _v3_error(field, "must be an object")
            decision_id = raw_ids[index]
            if base_index < len(decision_ids) and decision_id == decision_ids[base_index]:
                latest_base = decision_id
                base_index += 1
            elif _EXTRA_DECISION_ID.fullmatch(decision_id):
                if not latest_base:
                    _v3_error(f"{field}.id", "extra decisions must follow a base decision")
                if decision_id in extra_ids:
                    _v3_error(f"{field}.id", "must be unique")
                extra_ids.add(decision_id)
                if _text(raw.get("after")) != latest_base:
                    _v3_error(f"{field}.after", "must name the nearest preceding base decision")
                if not _text(raw.get("reason")):
                    _v3_error(f"{field}.reason", "must explain why this separate decision is needed")
            else:
                _v3_error(
                    f"{field}.id",
                    "must follow the base dependency order or use a unique extra_<slug> id",
                )
        if base_index != len(decision_ids):
            _v3_error(
                "wizard.decisions",
                "must include all base decisions in order: " + " -> ".join(decision_ids),
            )
    decisions: dict[str, dict[str, Any]] = {}
    axes: set[str] = set()
    for index, raw in enumerate(raw_decisions):
        field = f"wizard.decisions[{index}]"
        if not isinstance(raw, dict):
            _v3_error(field, "must be an object")
        decision_id = _text(raw.get("id"))
        is_extra = bool(_EXTRA_DECISION_ID.fullmatch(decision_id))
        if decision_id not in decision_ids and not is_extra:
            _v3_error(f"{field}.id", "is unknown")
        if decision_id in decisions:
            _v3_error(f"{field}.id", "must be unique")

        status = _text(raw.get("status"))
        if is_extra and not isinstance(raw.get("none_allowed"), bool):
            _v3_error(f"{field}.none_allowed", "must be a boolean")
        none_allowed = raw["none_allowed"] if is_extra else decision_id in _NONE_ALLOWED_DECISIONS
        expected_statuses = {"confirmed", "none"} if none_allowed else {"confirmed"}
        if status not in expected_statuses:
            if status in {"", "unresolved", "provisional"}:
                raise LedgerError(
                    "hatch_unresolved",
                    f"guided hatch decision is not confirmed: {decision_id}",
                    {"field": field, "decision_id": decision_id},
                )
            _v3_error(f"{field}.status", f"must be one of {sorted(expected_statuses)}")

        cardinality = _text(raw.get("cardinality"))
        if cardinality != "one":
            _v3_error(f"{field}.cardinality", "guided v3 uses one-path choices; must be one")
        if raw.get("custom_allowed") is not True:
            _v3_error(f"{field}.custom_allowed", "must be true")
        if bool(raw.get("none_allowed")) != none_allowed:
            _v3_error(f"{field}.none_allowed", f"must be {str(none_allowed).lower()}")

        source = _text(raw.get("source"))
        if source not in _DECISION_SOURCES:
            _v3_error(f"{field}.source", "is invalid")
        if status == "none" and source != "none":
            _v3_error(f"{field}.source", "must be none when status is none")
        if status == "confirmed" and source == "none":
            _v3_error(f"{field}.source", "cannot be none when status is confirmed")
        axis = _text(raw.get("axis"))
        if not axis:
            _v3_error(f"{field}.axis", "must name the single decision axis")
        if axis in axes:
            _v3_error(f"{field}.axis", "must be distinct from every other decision axis")
        axes.add(axis)
        if not _text(raw.get("summary")):
            _v3_error(f"{field}.summary", "must record the selected result")

        options = raw.get("options", [])
        if source == "author_supplied" and options in (None, []):
            options = []
        elif not isinstance(options, list) or not 2 <= len(options) <= 3:
            _v3_error(f"{field}.options", "must contain 2-3 comparable candidates")

        option_ids: list[str] = []
        for option_index, option in enumerate(options):
            option_field = f"{field}.options[{option_index}]"
            if not isinstance(option, dict):
                _v3_error(option_field, "must be an object")
            option_id = _text(option.get("id"))
            if not option_id:
                _v3_error(f"{option_field}.id", "is required")
            option_ids.append(option_id)
            for key in ("label", "outcome", "benefit", "cost", "risk"):
                if not _text(option.get(key)):
                    _v3_error(option_field, f"missing required field: {key}")
            if decision_id == "voice_style":
                option_voice_id = _text(option.get("voice_id"))
                if not option_voice_id:
                    _v3_error(f"{option_field}.voice_id", "must identify an available voice")
                resolve_voice_id(option_voice_id)
        if decision_id == "voice_style" and len({_text(option["voice_id"]) for option in options}) != len(options):
            _v3_error(f"{field}.options", "candidate voice_ids must be distinct")
        if len(set(option_ids)) != len(option_ids):
            _v3_error(f"{field}.options", "candidate ids must be unique")
        if option_ids and option_ids != list("ABC"[:len(option_ids)]):
            _v3_error(f"{field}.options", "candidate ids must be A/B or A/B/C in display order")
        for key in ("label", "outcome"):
            values = [_text(option.get(key)).casefold() for option in options]
            if len(set(values)) != len(values):
                _v3_error(f"{field}.options", f"candidate {key}s must be meaningfully distinct")

        selected = raw.get("selected", [])
        if not isinstance(selected, list) or any(not _text(item) for item in selected):
            _v3_error(f"{field}.selected", "must be a list of non-empty ids")
        selected_ids = [_text(item) for item in selected]
        if len(set(selected_ids)) != len(selected_ids):
            _v3_error(f"{field}.selected", "must not contain duplicates")
        if source in {"candidate", "default"}:
            if not selected_ids or any(item not in option_ids for item in selected_ids):
                _v3_error(f"{field}.selected", "must reference presented candidate ids")
            if cardinality == "one" and len(selected_ids) != 1:
                _v3_error(f"{field}.selected", "must contain exactly one id")
        elif source == "none":
            if selected_ids not in ([], ["none"]):
                _v3_error(f"{field}.selected", "must be empty or [none]")
        elif source in {"custom", "author_supplied"} and selected_ids:
            _v3_error(f"{field}.selected", "must be empty for custom or author-supplied values")

        recommended_id = _text(raw.get("recommended_id"))
        if recommended_id:
            if recommended_id not in option_ids:
                _v3_error(f"{field}.recommended_id", "must reference a candidate id")
            if not _text(raw.get("recommendation_reason")):
                _v3_error(f"{field}.recommendation_reason", "is required when recommending an option")
        if source == "default" and (not recommended_id or selected_ids != [recommended_id]):
            _v3_error(field, "default source must select the explicitly recommended candidate")
        if decision_id == "voice_style":
            voice_id = _text(raw.get("voice_id"))
            if not voice_id:
                _v3_error(f"{field}.voice_id", "must record the chosen voice id")
            resolve_voice_id(voice_id)
            if voice_id != _text(manifest.get("voice")):
                _v3_error(f"{field}.voice_id", "must match top-level voice")
            if source in {"candidate", "default"}:
                selected_voice_id = next(
                    _text(option["voice_id"])
                    for option in options
                    if _text(option.get("id")) == selected_ids[0]
                )
                if voice_id != selected_voice_id:
                    _v3_error(f"{field}.voice_id", "must match the selected candidate voice_id")
        decisions[decision_id] = raw

    missing = [item for item in decision_ids if item not in decisions]
    if missing:
        raise LedgerError(
            "hatch_unresolved",
            "guided hatch decisions are incomplete",
            {"field": "wizard.decisions", "missing": missing},
        )
    return decisions


def _validate_v3_mode_section(
    manifest: dict[str, Any],
    field: str,
    normalized: dict[str, Any],
    required: tuple[str, ...],
) -> None:
    raw = manifest.get(field, _MISSING)
    if not isinstance(raw, dict) or "mode" not in raw:
        raise LedgerError(
            "hatch_unresolved",
            f"guided hatch requires an explicit present/none decision for {field}",
            {"field": field},
        )
    mode = normalized.get("mode")
    if mode not in {"present", "none"}:
        if mode == "unresolved":
            raise LedgerError("hatch_unresolved", f"{field} is unresolved", {"field": field})
        _v3_error(field, "mode must be present or none")
    if mode == "none":
        payload = [key for key, value in raw.items() if key != "mode" and value not in (None, "", [], {})]
        if payload:
            _v3_error(field, "mode none must not carry story content: " + ", ".join(sorted(payload)))
        return
    if not normalized.get("_shape_valid", True):
        _v3_error(field, "must use the documented object shape")
    # v3 is a single canonical contract: aliases from older manifests are not
    # accepted, even if the renderer could otherwise normalize them.
    missing = [key for key in required if not _text(raw.get(key))]
    if missing:
        _v3_error(field, "missing required fields: " + ", ".join(missing))


def _validate_relationship_structure(manifest: dict[str, Any]) -> dict[str, Any]:
    raw = manifest.get("relationship_structure")
    if not isinstance(raw, dict) or "mode" not in raw:
        raise LedgerError(
            "hatch_unresolved",
            "guided hatch requires an explicit relationship_structure present/none decision",
            {"field": "relationship_structure"},
        )
    mode = _text(raw.get("mode")).lower()
    if mode == "none":
        payload = [key for key, value in raw.items() if key != "mode" and value not in (None, "", [], {})]
        if payload:
            _v3_error("relationship_structure", "mode none must not carry relationship content")
        return raw
    if mode != "present":
        _v3_error("relationship_structure.mode", "must be present or none")
